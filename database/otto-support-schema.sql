CREATE OR REPLACE FUNCTION otto_a1.close_support_ticket_user(
  p_user_id uuid,
  p_ticket_id uuid
)
RETURNS void
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = otto_a1, public
AS $$
DECLARE
  v_owner uuid;
  v_status text;
BEGIN
  SELECT t.user_id, t.status
  INTO v_owner, v_status
  FROM otto_a1.support_tickets t
  WHERE t.id = p_ticket_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'support_ticket_not_found';
  END IF;
  IF v_owner <> p_user_id THEN
    RAISE EXCEPTION 'support_ticket_forbidden';
  END IF;
  IF v_status = 'closed' THEN
    RETURN;
  END IF;

  UPDATE otto_a1.support_tickets
  SET status = 'closed',
      updated_at = now(),
      closed_at = now(),
      closed_by = 'user',
      closed_by_admin = NULL,
      user_last_read_at = now()
  WHERE id = p_ticket_id;
END;
$$;

