BEGIN;

CREATE TABLE IF NOT EXISTS otto_a1.support_tickets (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  ticket_no bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE NOT NULL,
  user_id uuid NOT NULL REFERENCES otto_a1.users(id) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'closed')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  last_message_at timestamptz NOT NULL DEFAULT now(),
  last_message_author text NOT NULL DEFAULT 'user' CHECK (last_message_author IN ('user', 'admin')),
  user_last_read_at timestamptz,
  admin_last_read_at timestamptz,
  closed_at timestamptz,
  closed_by text CHECK (closed_by IS NULL OR closed_by IN ('user', 'admin')),
  closed_by_admin text,
  page_url text NOT NULL DEFAULT '',
  user_agent text NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS otto_a1.support_messages (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  ticket_id uuid NOT NULL REFERENCES otto_a1.support_tickets(id) ON DELETE CASCADE,
  author_type text NOT NULL CHECK (author_type IN ('user', 'admin')),
  body text NOT NULL CHECK (char_length(btrim(body)) BETWEEN 1 AND 8000),
  admin_login text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (
    (author_type = 'user' AND admin_login IS NULL)
    OR
    (author_type = 'admin' AND admin_login IS NOT NULL AND char_length(btrim(admin_login)) BETWEEN 1 AND 120)
  )
);

CREATE INDEX IF NOT EXISTS support_tickets_user_created_idx
  ON otto_a1.support_tickets (user_id, created_at DESC);

CREATE INDEX IF NOT EXISTS support_tickets_queue_idx
  ON otto_a1.support_tickets (status, last_message_author, last_message_at);

CREATE INDEX IF NOT EXISTS support_messages_ticket_created_idx
  ON otto_a1.support_messages (ticket_id, created_at, id);

GRANT SELECT, INSERT, UPDATE, DELETE ON otto_a1.support_tickets TO otto_a1_api;
GRANT SELECT, INSERT, UPDATE, DELETE ON otto_a1.support_messages TO otto_a1_api;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA otto_a1 TO otto_a1_api;

CREATE OR REPLACE FUNCTION otto_a1.create_support_ticket(
  p_user_id uuid,
  p_message text,
  p_page_url text DEFAULT '',
  p_user_agent text DEFAULT ''
)
RETURNS TABLE(ticket_id uuid, ticket_number bigint, created_at timestamptz)
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = otto_a1, public
AS $$
DECLARE
  v_now timestamptz := now();
  v_day_start timestamptz;
  v_count integer;
  v_ticket_id uuid;
  v_ticket_no bigint;
BEGIN
  IF p_user_id IS NULL OR COALESCE(char_length(btrim(p_message)), 0) NOT BETWEEN 1 AND 8000 THEN
    RAISE EXCEPTION 'support_invalid_message';
  END IF;

  PERFORM pg_advisory_xact_lock(hashtextextended(p_user_id::text, 0));

  v_day_start := date_trunc('day', v_now AT TIME ZONE 'Europe/Moscow') AT TIME ZONE 'Europe/Moscow';

  SELECT count(*)::integer
  INTO v_count
  FROM otto_a1.support_tickets t
  WHERE t.user_id = p_user_id
    AND t.created_at >= v_day_start
    AND t.created_at < v_day_start + interval '1 day';

  IF v_count >= 5 THEN
    RAISE EXCEPTION 'support_daily_limit';
  END IF;

  INSERT INTO otto_a1.support_tickets (
    user_id,
    status,
    created_at,
    updated_at,
    last_message_at,
    last_message_author,
    user_last_read_at,
    page_url,
    user_agent
  ) VALUES (
    p_user_id,
    'open',
    v_now,
    v_now,
    v_now,
    'user',
    v_now,
    left(COALESCE(p_page_url, ''), 2000),
    left(COALESCE(p_user_agent, ''), 1000)
  )
  RETURNING id, ticket_no INTO v_ticket_id, v_ticket_no;

  INSERT INTO otto_a1.support_messages (
    ticket_id,
    author_type,
    body,
    created_at
  ) VALUES (
    v_ticket_id,
    'user',
    btrim(p_message),
    v_now
  );

  RETURN QUERY SELECT v_ticket_id, v_ticket_no, v_now;
END;
$$;

CREATE OR REPLACE FUNCTION otto_a1.reply_support_ticket_user(
  p_user_id uuid,
  p_ticket_id uuid,
  p_message text
)
RETURNS TABLE(message_id uuid, created_at timestamptz)
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = otto_a1, public
AS $$
DECLARE
  v_now timestamptz := now();
  v_owner uuid;
  v_status text;
  v_last_user_message timestamptz;
  v_message_id uuid;
BEGIN
  IF p_user_id IS NULL OR p_ticket_id IS NULL OR COALESCE(char_length(btrim(p_message)), 0) NOT BETWEEN 1 AND 8000 THEN
    RAISE EXCEPTION 'support_invalid_message';
  END IF;

  SELECT t.user_id, t.status
  INTO v_owner, v_status
  FROM otto_a1.support_tickets t
  WHERE t.id = p_ticket_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'support_ticket_not_found';
  END IF;
  IF v_owner <> p_user_id THEN
    RAISE EXCEPTION 'support_ticket_forbidden';
  END IF;
  IF v_status <> 'open' THEN
    RAISE EXCEPTION 'support_ticket_closed';
  END IF;

  SELECT max(m.created_at)
  INTO v_last_user_message
  FROM otto_a1.support_messages m
  WHERE m.ticket_id = p_ticket_id
    AND m.author_type = 'user';

  IF v_last_user_message IS NOT NULL AND v_last_user_message > v_now - interval '2 seconds' THEN
    RAISE EXCEPTION 'support_message_rate_limit';
  END IF;

  INSERT INTO otto_a1.support_messages (
    ticket_id,
    author_type,
    body,
    created_at
  ) VALUES (
    p_ticket_id,
    'user',
    btrim(p_message),
    v_now
  )
  RETURNING id INTO v_message_id;

  UPDATE otto_a1.support_tickets
  SET updated_at = v_now,
      last_message_at = v_now,
      last_message_author = 'user',
      user_last_read_at = v_now
  WHERE id = p_ticket_id;

  RETURN QUERY SELECT v_message_id, v_now;
END;
$$;

