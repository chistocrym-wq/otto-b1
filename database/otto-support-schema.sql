CREATE OR REPLACE FUNCTION otto_a1.support_user_summary(
  p_user_id uuid
)
RETURNS TABLE(unread_count bigint, latest_ticket_id uuid, latest_ticket_no bigint)
LANGUAGE sql
SECURITY INVOKER
SET search_path = otto_a1, public
AS $$
  SELECT
    count(*)::bigint AS unread_count,
    (
      SELECT t2.id
      FROM otto_a1.support_tickets t2
      WHERE t2.user_id = p_user_id
        AND t2.last_message_author = 'admin'
        AND (t2.user_last_read_at IS NULL OR t2.user_last_read_at < t2.last_message_at)
      ORDER BY t2.last_message_at DESC
      LIMIT 1
    ) AS latest_ticket_id,
    (
      SELECT t3.ticket_no
      FROM otto_a1.support_tickets t3
      WHERE t3.user_id = p_user_id
        AND t3.last_message_author = 'admin'
        AND (t3.user_last_read_at IS NULL OR t3.user_last_read_at < t3.last_message_at)
      ORDER BY t3.last_message_at DESC
      LIMIT 1
    ) AS latest_ticket_no
  FROM otto_a1.support_tickets t
  WHERE t.user_id = p_user_id
    AND t.last_message_author = 'admin'
    AND (t.user_last_read_at IS NULL OR t.user_last_read_at < t.last_message_at);
$$;

CREATE OR REPLACE FUNCTION otto_a1.support_user_list(
  p_user_id uuid
)
RETURNS TABLE(
  ticket_id uuid,
  ticket_no bigint,
  status text,
  created_at timestamptz,
  updated_at timestamptz,
  last_message_at timestamptz,
  last_message_author text,
  user_unread boolean,
  closed_at timestamptz
)
LANGUAGE sql
SECURITY INVOKER
SET search_path = otto_a1, public
AS $$
  SELECT
    t.id,
    t.ticket_no,
    t.status,
    t.created_at,
    t.updated_at,
    t.last_message_at,
    t.last_message_author,
    (
      t.last_message_author = 'admin'
      AND (t.user_last_read_at IS NULL OR t.user_last_read_at < t.last_message_at)
    ) AS user_unread,
    t.closed_at
  FROM otto_a1.support_tickets t
  WHERE t.user_id = p_user_id
  ORDER BY
    CASE WHEN t.status = 'open' THEN 0 ELSE 1 END,
    t.last_message_at DESC;
$$;

CREATE OR REPLACE FUNCTION otto_a1.support_admin_stats()
RETURNS TABLE(
  total_users bigint,
  registered_today bigint,
  open_tickets bigint,
  waiting_support bigint
)
LANGUAGE sql
SECURITY INVOKER
SET search_path = otto_a1, public
AS $$
  WITH bounds AS (
    SELECT date_trunc('day', now() AT TIME ZONE 'Europe/Moscow') AT TIME ZONE 'Europe/Moscow' AS day_start
  )
  SELECT
    (SELECT count(*)::bigint FROM otto_a1.users),
    (
      SELECT count(*)::bigint
      FROM otto_a1.users u, bounds b
      WHERE u.created_at >= b.day_start
        AND u.created_at < b.day_start + interval '1 day'
    ),
    (
      SELECT count(*)::bigint
      FROM otto_a1.support_tickets t
      WHERE t.status = 'open'
    ),
    (
      SELECT count(*)::bigint
      FROM otto_a1.support_tickets t
      WHERE t.status = 'open'
        AND t.last_message_author = 'user'
    );
$$;

CREATE OR REPLACE FUNCTION otto_a1.support_admin_list(
  p_filter text DEFAULT 'waiting',
  p_limit integer DEFAULT 50,
  p_offset integer DEFAULT 0
)
RETURNS TABLE(
  ticket_id uuid,
  ticket_no bigint,
  user_id uuid,
  user_name text,
  status text,
  created_at timestamptz,
  updated_at timestamptz,
  last_message_at timestamptz,
  last_message_author text,
  admin_unread boolean,
  closed_at timestamptz,
  total_count bigint
)
LANGUAGE sql
SECURITY INVOKER
SET search_path = otto_a1, public
AS $$
  WITH filtered AS (
    SELECT
      t.id AS ticket_id,
      t.ticket_no,
      t.user_id,
      COALESCE(NULLIF(btrim(p.name), ''), 'Без имени') AS user_name,
      t.status,
      t.created_at,
      t.updated_at,
      t.last_message_at,
      t.last_message_author,
      (
        t.last_message_author = 'user'
        AND (t.admin_last_read_at IS NULL OR t.admin_last_read_at < t.last_message_at)
      ) AS admin_unread,
      t.closed_at
    FROM otto_a1.support_tickets t
    LEFT JOIN otto_a1.user_profiles p ON p.user_id = t.user_id
    WHERE
      (p_filter = 'waiting' AND t.status = 'open' AND t.last_message_author = 'user')
      OR (p_filter = 'open' AND t.status = 'open')
      OR (p_filter = 'closed' AND t.status = 'closed')
      OR (p_filter = 'all')
  )
  SELECT
    f.ticket_id,
    f.ticket_no,
    f.user_id,
    f.user_name,
    f.status,
    f.created_at,
    f.updated_at,
    f.last_message_at,
    f.last_message_author,
    f.admin_unread,
    f.closed_at,
    count(*) OVER () AS total_count
  FROM filtered f
  ORDER BY
    CASE WHEN f.status = 'open' AND f.last_message_author = 'user' THEN 0
         WHEN f.status = 'open' THEN 1
         ELSE 2 END,
    CASE WHEN f.status = 'open' AND f.last_message_author = 'user' THEN f.last_message_at END ASC,
    f.last_message_at DESC
  LIMIT LEAST(GREATEST(COALESCE(p_limit, 50), 1), 100)
  OFFSET GREATEST(COALESCE(p_offset, 0), 0);
$$;

